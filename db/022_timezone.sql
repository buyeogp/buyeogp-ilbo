-- 022 DB 시간대를 한국으로 — 「오늘」이 한국 날짜여야 한다
--
-- Supabase 기본 시간대는 UTC 다. 그러면 한국 시각 00:00~09:00 동안
-- current_date 가 **어제**가 된다 (2026-09-29 08:34 KST 에 current_date = 09-28).
--
-- current_date 에 걸린 것:
--   · 담당 돈사·등급의 적용일 (014 RLS · 세션 · 관리 화면) — 「오늘부터」 배정한
--     담당이 오전 9시까지 안 보이고, 오늘부로 끝낸 담당이 9시까지 남는다
--   · 약품 휴약기간 남은 날 · 출하 차단 (013 v_withdrawal)
--   · 기한 지난 백신 · 계류 일수 (013)
--   · 새 계정·담당의 기본 적용일 (002 · 003 DEFAULT current_date)
-- 현장은 아침 일찍 입력을 시작하므로 이 9시간이 실제로 쓰이는 시간이다.
--
-- 데이터베이스 기본값으로 건다 — 앱·관리·마이그레이션 계정 모두 새 연결부터 한국 시각을 쓴다.
-- 이미 열린 연결에는 적용되지 않으므로 적용 뒤 api 를 다시 띄운다.
-- timestamptz 로 저장된 값은 그대로다(같은 순간을 다른 표기로 보여 줄 뿐).
-- =====================================================================
DO $$
BEGIN
  EXECUTE format('ALTER DATABASE %I SET timezone TO %L', current_database(), 'Asia/Seoul');
END $$;

-- 이 트랜잭션 안의 나머지도 한국 시각으로
SET LOCAL timezone TO 'Asia/Seoul';
